"""
Alembic environment.

Two entry points:
* the app (db/migrate.py) passes an open connection in `config.attributes`;
* the `alembic` CLI has none, so one is opened from `settings.database_url`.

`render_as_batch` makes autogenerated ALTERs work on SQLite (which rebuilds the
table); other dialects get plain ALTER TABLE statements.
"""

import asyncio
from datetime import datetime
from typing import Any
from zoneinfo import ZoneInfo

import sqlalchemy as sa
from alembic import context
from alembic.runtime.migration import MigrationContext
from sqlalchemy import Connection
from sqlalchemy.ext.asyncio import create_async_engine

import models  # noqa: F401  (registers tables on Base.metadata)
from config import settings
from database import Base

target_metadata = Base.metadata


def _compare_type(
    ctx: MigrationContext,
    inspected_column: Any,
    metadata_column: Any,
    inspected_type: sa.types.TypeEngine[Any],
    metadata_type: sa.types.TypeEngine[Any],
) -> bool | None:
    """SQLite stores FLOAT and DOUBLE alike (8-byte REAL); databases created before
    the models switched to Double say FLOAT. Not a real difference there."""
    if (
        ctx.dialect.name == "sqlite"
        and isinstance(inspected_type, sa.Float)
        and isinstance(metadata_type, sa.Float)
    ):
        return False
    return None  # Alembic's default comparison


def _timestamp_ids(ctx: MigrationContext, revision: Any, directives: list[Any]) -> None:
    """New revisions get a creation-time id (YYYYMMDD_HHMMSS) instead of random hex,
    matching the file name (alembic.ini `file_template`)."""
    if directives:
        directives[0].rev_id = datetime.now(ZoneInfo(settings.timezone)).strftime(
            "%Y%m%d_%H%M%S"
        )


def _run(connection: Connection) -> None:
    context.configure(
        connection=connection,
        target_metadata=target_metadata,
        render_as_batch=True,
        compare_type=_compare_type,
        process_revision_directives=_timestamp_ids,
    )
    with context.begin_transaction():
        context.run_migrations()


async def _run_cli() -> None:
    engine = create_async_engine(settings.database_url)
    async with engine.begin() as conn:
        await conn.run_sync(_run)
    await engine.dispose()


if context.is_offline_mode():
    raise SystemExit("Offline (--sql) mode is not supported; run against a database.")

shared = context.config.attributes.get("connection")
if shared is not None:
    _run(shared)
else:
    asyncio.run(_run_cli())

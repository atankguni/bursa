"""
Regenerate `market/idx_listed.py` from IDX's public stock-listing endpoint.

The endpoint is behind Cloudflare, so we use curl_cffi browser impersonation
(already a backend dependency via yfinance).

Usage (inside the backend environment):
    python scripts/gen_idx_list.py [out_path]

Defaults to writing ../market/idx_listed.py. Source: idx.co.id.
"""

import sys
from pathlib import Path

from curl_cffi import requests

URL = (
    "https://www.idx.co.id/primary/StockData/GetSecuritiesStock"
    "?start=0&length=3000&language=en-us"
)


def fetch() -> dict[str, str]:
    resp = requests.get(URL, impersonate="chrome", timeout=40)
    resp.raise_for_status()
    data = resp.json()
    rows: dict[str, str] = {}
    for x in data.get("data", []):
        code = (x.get("Code") or "").strip().upper()
        if code:
            rows[f"{code}.JK"] = (x.get("Name") or "").strip()
    return dict(sorted(rows.items()))


def main() -> None:
    out = (
        Path(sys.argv[1])
        if len(sys.argv) > 1
        else Path(__file__).resolve().parent.parent / "market" / "idx_listed.py"
    )
    rows = fetch()
    with out.open("w", encoding="utf-8") as f:
        f.write('"""\n')
        f.write("market/idx_listed.py\n")
        f.write("--------------------\n")
        f.write("Full list of IDX (Bursa Efek Indonesia) listed companies.\n\n")
        f.write("Generated by scripts/gen_idx_list.py (source: idx.co.id).\n")
        f.write("Regenerate periodically as listings change.\n")
        f.write('"""\n\n')
        f.write("LISTED: dict[str, str] = {\n")
        for ticker, name in rows.items():
            f.write(f"    {ticker!r}: {name!r},\n")
        f.write("}\n")
    print(f"wrote {len(rows)} entries to {out}")


if __name__ == "__main__":
    main()
